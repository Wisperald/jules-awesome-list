    def curve(fn, col, lab, dash=""):
        pts = [(sx(d / 4), y1 - (y1 - y0) * fn(d / 4)) for d in range(4, 113)]
        path = "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts)
