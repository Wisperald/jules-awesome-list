# сдвиг подписей, чтобы не перекрывать соседние
LABEL_SIDE = {"GV": 1, "CV": 1}


def _flags(mer):
    return {int(p["num"]): p["flags"] for p in POINTS[mer]}


def svg_view(view, layers, scale=1.0, labels=True, title=None, crop=None):
    w, h, fn = VIEWS[view]
    vb = crop or (0, 0, w, h)
    s = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb[0]} {vb[1]} {vb[2]} {vb[3]}" '
         f'class="map">']
    s.append(fn())
    for mer, seq in layers:
        col = COLORS[mer]
        fl = _flags(mer)
        segs, cur = [], []
        for item in seq:
            if item is None:
                if cur:
                    segs.append(cur)
                cur = []
            else:
                cur.append(item)
        if cur:
            segs.append(cur)
        for sg in segs:
            if len(sg) > 1:
                d = "M" + " L".join(f"{x},{y}" for _, x, y in sg)
                s.append(f'<path d="{d}" fill="none" stroke="{col}" stroke-width="1.6" '
                         f'stroke-opacity=".75" stroke-linejoin="round"/>')
        for sg in segs:
            for n, x, y in sg:
                f = fl.get(n, "")
                if "T" in f:
                    s.append(f'<circle cx="{x}" cy="{y}" r="4.2" fill="none" stroke="#111" stroke-width=".9"/>')
                s.append(f'<circle cx="{x}" cy="{y}" r="2.3" fill="{col}" stroke="#fff" stroke-width=".6"/>')
                if labels:
                    dx = 4 if (x >= 150 or LABEL_SIDE.get(mer)) else -4
                    anchor = "start" if dx > 0 else "end"
                    s.append(f'<text x="{x + dx}" y="{y + 2}" text-anchor="{anchor}" class="pl">{n}</text>')
    s.append("</svg>")
    return "".join(s)


def _crop(view, seq, margin=28, minw=130, minh=170):
    w, h, _ = VIEWS[view]
    pts = [(x, y) for it in seq if it for _, x, y in [it]]
    x0 = min(p[0] for p in pts) - margin; x1 = max(p[0] for p in pts) + margin
    y0 = min(p[1] for p in pts) - margin; y1 = max(p[1] for p in pts) + margin
    if x1 - x0 < minw:
        c = (x0 + x1) / 2; x0, x1 = c - minw / 2, c + minw / 2
    if y1 - y0 < minh:
        c = (y0 + y1) / 2; y0, y1 = c - minh / 2, c + minh / 2
    x0, y0 = max(0, x0), max(0, y0)
    x1, y1 = min(w, x1), min(h, y1)
    return (round(x0), round(y0), round(x1 - x0), round(y1 - y0))


def meridian_figure(mer):
    parts = []
    for view, seq in ANCH[mer]:
        crop = _crop(view, seq)
        parts.append((view, svg_view(view, [(mer, seq)], crop=crop)))
    return parts


def overview(view):
    layers = []
    for mer, lst in ANCH.items():
        for v, seq in lst:
            if v == view:
                layers.append((mer, seq))
    return svg_view(view, layers, labels=False)


