def organ_clock():
    import math
    order = ["LU", "LI", "ST", "SP", "HT", "SI", "BL", "KI", "PC", "TE", "GB", "LR"]
    names = {"LU": "Лёгкие", "LI": "Толст. кишка", "ST": "Желудок", "SP": "Селезёнка", "HT": "Сердце",
             "SI": "Тонк. кишка", "BL": "Моч. пузырь", "KI": "Почки", "PC": "Перикард", "TE": "Тр. обогрев.",
             "GB": "Желч. пузырь", "LR": "Печень"}
    cx, cy, R, r = 200, 200, 175, 80
    out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 400" class="clock">']
    for i, m in enumerate(order):
        start_h = 3 + 2 * i
        a0 = math.radians(start_h / 24 * 360 - 90)
        a1 = math.radians((start_h + 2) / 24 * 360 - 90)
        p = lambda a, rr: (cx + rr * math.cos(a), cy + rr * math.sin(a))
        x0, y0 = p(a0, R); x1, y1 = p(a1, R); x2, y2 = p(a1, r); x3, y3 = p(a0, r)
        out.append(f'<path d="M{x0:.1f},{y0:.1f} A{R},{R} 0 0 1 {x1:.1f},{y1:.1f} L{x2:.1f},{y2:.1f} '
                   f'A{r},{r} 0 0 0 {x3:.1f},{y3:.1f} Z" fill="{COLORS[m]}" fill-opacity=".85" stroke="#fff" stroke-width="2"/>')
        am = (a0 + a1) / 2
        tx, ty = p(am, (R + r) / 2)
        out.append(f'<text x="{tx:.1f}" y="{ty - 3:.1f}" text-anchor="middle" class="ck">{m}</text>')
        out.append(f'<text x="{tx:.1f}" y="{ty + 9:.1f}" text-anchor="middle" class="ck2">{names[m]}</text>')
        hx, hy = p(a0, R + 12)
        out.append(f'<text x="{hx:.1f}" y="{hy + 3:.1f}" text-anchor="middle" class="ck3">{start_h % 24:02d}</text>')
    out.append(f'<circle cx="{cx}" cy="{cy}" r="{r - 6}" fill="#0f1b2d"/>'
               f'<text x="{cx}" y="{cy - 6}" text-anchor="middle" fill="#fff" font-size="14" font-weight="700">子午流注</text>'
               f'<text x="{cx}" y="{cy + 12}" text-anchor="middle" fill="#cbd5e1" font-size="9">«суточные часы органов»</text>'
               f'<text x="{cx}" y="{cy + 24}" text-anchor="middle" fill="#cbd5e1" font-size="8">традиционная модель</text>')
    out.append("</svg>")
    return "".join(out)


